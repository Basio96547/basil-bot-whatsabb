#!/data/data/com.termux/files/usr/bin/sh
# يتأكد أن الإعداد الجديد يُقلع قبل أن نمسّ الخدمة الحيّة.
#
# config.ts يفشل عمداً عند الإقلاع على أي خلل (مفتاح مشروع ناقص، رقم غير
# صالح في projects.json، قالب مكسور، مفتاحا API متطابقان). هذا الفشل المبكر
# جيد في التطوير، لكنه على الجوال كان يعني: pm2 delete ثم start لنسخة لا
# تُقلع = حلقة انهيار كل ٣ ثوانٍ وتوقّف التحقق لكل المواقع. هنا يُحمَّل
# الإعداد وحده (بلا قاعدة بيانات، بلا واتساب) — إن فشل خرجنا والخدمة القديمة
# ما زالت تعمل من ذاكرتها.

cd "$(dirname "$0")/.."
if node --import tsx --input-type=module -e "await import('./src/config.ts')"; then
  echo "  الإعداد سليم"
else
  echo ""
  echo "  !!! الإعداد الجديد لا يُقلع — لم يُعَد تشغيل شيء، والخدمة الحالية ما زالت تعمل."
  echo "  !!! أصلح السبب أعلاه (غالباً مفتاح ناقص في .env) ثم أعد التشغيل."
  exit 1
fi
