// نوم يستطيع الطرف المنتِج قطعه.
//
// كانت حلقة الإرسال تستيقظ كل ٥ ثوانٍ إلى الأبد لتسأل SQLite "هل وصل شيء؟".
// على خادم عادي هذا لا يُلاحَظ، أما على جوال فهو ~١٧ ألف إيقاظ للمعالج يومياً
// بلا سبب: الجهاز لا ينزل أبداً إلى النوم العميق، فيظل دافئاً على مدار الساعة
// مقابل لا شيء. الحل ليس إبطاء النبضة وحدها — ذلك يؤخّر رمز التحقق — بل جعل
// الحلقة تتراجع تدريجياً عند الخمول ويوقظها enqueue() فوراً عند وصول رسالة.
// النتيجة: إيقاظات أقل بكثير، وزمن استجابة أفضل من النبضة القديمة لا أسوأ.

// واحد فقط في كل لحظة — وهذا مقصود: العامل حلقة واحدة، ولو صار أكثر من منتظِر
// فالإشارة ستوقظ الأخير فقط، وهو ما يخفي الخطأ بدل أن يُظهره.
let wake: (() => void) | null = null;

// عدّاد لكل إشارة، سواء وجدت منتظِراً أم لا. الإشارة نفسها لا تُخزَّن (راجع
// الاختبار: انتظار جديد لا يُصرف على إشارة قديمة)، لكن إشارة وصلت والعامل
// مشغول بدفعة لم يُرسل منها شيئاً كانت تضيع كلياً، فينام بعدها دورة خمول
// كاملة (حتى دقيقة) ورسالة جديدة تنتظره. العامل يقرأ العدّاد قبل جلب الدفعة
// ويتخطّى النوم إن تغيّر.
let signals = 0;

/** يقطع انتظار العامل الآن. آمن في أي وقت، حتى لو لم يكن ينتظر. */
export function notifyWork(): void {
  signals += 1;
  wake?.();
}

/** عدد الإشارات منذ الإقلاع — تغيّره يعني أن عملاً وصل منذ آخر قراءة. */
export function workSignals(): number {
  return signals;
}

/** ينام `ms` ما لم يوقظه notifyWork() قبل ذلك. */
export function sleepUnlessWoken(ms: number): Promise<void> {
  return new Promise((resolve) => {
    const finish = (): void => {
      clearTimeout(timer);
      if (wake === finish) wake = null;
      resolve();
    };
    const timer = setTimeout(finish, ms);
    wake = finish;
  });
}
